// A small provenance cache lets t()-generated text inserted into the DOM switch
// languages too, without heuristically replacing arbitrary English/Kazakh words.
const emitted = new Map();
function readLanguage() {
  try { const value = globalThis.localStorage?.getItem(STORAGE_KEY); return LANGUAGES.has(value) ? value : 'ru'; }
  catch { return 'ru'; }
}
function remember(output, source) {
  if (output === source) return output;
  if (emitted.size >= 2048) emitted.delete(emitted.keys().next().value);
  emitted.set(output, source);
  return output;
}

/** Format elapsed seconds without locale-dependent digits or a 60-minute wrap. */
export function formatDuration(seconds) {
  const value = Number(seconds);
  const whole = Number.isFinite(value) ? Math.max(0, Math.floor(value)) : 0;
  return `${Math.floor(whole / 60)}:${String(whole % 60).padStart(2, '0')}`;
}

/** Analytics use explicit units; chart ticks retain the compact m:ss formatter. */
export function formatElapsed(seconds) {
  const value=Number(seconds),whole=Number.isFinite(value)?Math.max(0,Math.floor(value)):0;
  return t(`${Math.floor(whole/60)} мин ${whole%60} сек`);
}

/** Translate a Russian UI string; unknown text and all captured user data survive. */
export function t(text) {
  if (text == null) return '';
  const input = String(text);
  const source = emitted.get(input) ?? input;
  if (language === 'ru') return source;
  const match = /^(\s*)([\s\S]*?)(\s*)$/.exec(source);
  const translated = translateCore(match[2]);
  return remember(match[1] + translated + match[3], source);
}

